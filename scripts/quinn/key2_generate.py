#!/usr/bin/env python3
"""Key 2 free-generation runner - greedy, 256 bytes, one sample per prompt.

This is the generation half of the key-2 instrument
(`docs/notes/2026-11-19_key2-coherence-rubric.md`, section 8). It does not
score anything; it produces the samples the judges score.

Contract:
  - prompt set: `data/evals/key2_prompts_v1.json`, 133 authored prompts,
    prompt <= 128 bytes, 100 gate (50 explain + 50 describe) + 33 argue
    diagnostic;
  - decoding: greedy argmax at temperature 0, one sample per prompt;
  - output: exactly 256 generated bytes per prompt, unless the model emits
    EOS (vocab is byte-level, so there is no EOS);
  - prompt + sample <= block_size (512), checked before the run.

The checkpoint is loaded through `pipeline.merge.load_model_mmap`, which keeps
the optimizer state file-backed. One checkpoint, full width, no neuron mask:
the negative reference is the base 3.62B model, not a routed arm.

Output is JSONL, one row per prompt, plus a meta JSON. The row keeps the exact
bytes as hex; `sample_text` is a UTF-8 decoding with replacement characters for
judge display only. Resume skips prompt ids already present in the JSONL.

Usage:
    .venv/bin/python scripts/quinn/key2_generate.py \
        --checkpoint out/routed_probe/bdh_textmix_p3_mixed_best.pt \
        --out out/key2_calibration/gen_3.62b.jsonl \
        --meta-out out/key2_calibration/gen_3.62b.meta.json \
        --log out/key2_calibration/gen_3.62b.log

Smoke test (one prompt, then stop):
    .venv/bin/python scripts/quinn/key2_generate.py --limit 1 ...

Validate the prompt file without loading the model:
    .venv/bin/python scripts/quinn/key2_generate.py --dry-run
"""

import argparse
import hashlib
import json
import os
import platform
import subprocess
import sys
import time

import torch

sys.path.insert(0, ".")

DEFAULT_PROMPTS = "data/evals/key2_prompts_v1.json"
DEFAULT_MAX_NEW_BYTES = 256
DEFAULT_PROMPT_MAX_BYTES = 128


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_head():
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], stderr=subprocess.DEVNULL
        ).decode().strip()
    except Exception:
        return None


def load_prompts(path, prompt_max_bytes):
    doc = json.load(open(path))
    rows = doc.get("prompts")
    if not isinstance(rows, list):
        raise SystemExit("%s: missing prompts[]" % path)
    seen = set()
    out = []
    for r in rows:
        pid = r.get("id")
        prompt = r.get("prompt")
        if not pid or not prompt:
            raise SystemExit("%s: row without id/prompt: %r" % (path, r))
        if pid in seen:
            raise SystemExit("%s: duplicate id %s" % (path, pid))
        seen.add(pid)
        b = prompt.encode("utf-8")
        if len(b) > prompt_max_bytes:
            raise SystemExit(
                "%s: %s is %d bytes, over the %d-byte prompt cap"
                % (path, pid, len(b), prompt_max_bytes)
            )
        out.append({
            "id": pid,
            "family": r.get("family"),
            "gate": bool(r.get("gate")),
            "prompt": prompt,
            "prompt_bytes": len(b),
            "prompt_sha256": hashlib.sha256(b).hexdigest(),
        })
    counts = {
        "total": len(out),
        "gate": sum(1 for r in out if r["gate"]),
        "diagnostic": sum(1 for r in out if not r["gate"]),
        "families": {},
    }
    for r in out:
        counts["families"][r["family"]] = counts["families"].get(r["family"], 0) + 1
    return doc, out, counts


@torch.no_grad()
def greedy_bytes(model, prompt, max_new_bytes, device):
    """Greedy argmax over byte tokens. Returns generated bytes only."""
    idx = torch.tensor(list(prompt), dtype=torch.long, device=device).unsqueeze(0)
    block = model.config.block_size
    if block is not None and len(prompt) + max_new_bytes > block:
        raise ValueError(
            "prompt %d + sample %d exceeds block_size %d"
            % (len(prompt), max_new_bytes, block)
        )
    start = idx.shape[1]
    for _ in range(max_new_bytes):
        idx_cond = idx[:, -block:] if block is not None else idx
        # collect_state=False: greedy decoding discards the returned state, and
        # the per-layer KV state (4 x (1,16,512,N) fp32 here) is the difference
        # between fitting and a global OOM on the GB10 unified pool. Logits are
        # bit-identical with and without it (2026-11-07 OOM note); every other
        # eval script in the repo already passes it.
        logits, _, _ = model(idx_cond, collect_state=False)
        nxt = torch.argmax(logits[:, -1, :], dim=-1, keepdim=True)
        idx = torch.cat((idx, nxt), dim=1)
    return bytes(idx[0, start:].to(torch.uint8).cpu().tolist())


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--checkpoint", help="checkpoint path (required unless --dry-run)")
    ap.add_argument("--prompts", default=DEFAULT_PROMPTS)
    ap.add_argument("--out", default="out/key2_calibration/gen_3.62b.jsonl")
    ap.add_argument("--meta-out", default="out/key2_calibration/gen_3.62b.meta.json")
    ap.add_argument("--log", default="out/key2_calibration/gen_3.62b.log")
    ap.add_argument("--max-new-bytes", type=int, default=DEFAULT_MAX_NEW_BYTES)
    ap.add_argument("--prompt-max-bytes", type=int, default=DEFAULT_PROMPT_MAX_BYTES)
    ap.add_argument("--limit", type=int, default=0, help="stop after N prompts")
    ap.add_argument("--ids", default="", help="comma-separated prompt ids to run")
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--dtype", default="auto", choices=("auto", "float32"),
                    help="auto keeps the checkpoint dtype; bfloat16 is not supported "
                         "(the attention frequency buffer is float32)")
    ap.add_argument("--resume", action="store_true", help="skip ids already in --out")
    ap.add_argument("--hash-checkpoint", action="store_true",
                    help="sha256 the checkpoint (slow, but makes the provenance exact)")
    ap.add_argument("--dry-run", action="store_true", help="validate the prompt set only")
    args = ap.parse_args()

    doc, prompts, counts = load_prompts(args.prompts, args.prompt_max_bytes)
    if args.max_new_bytes <= 0:
        raise SystemExit("--max-new-bytes must be positive")
    if counts["total"] != 133 or counts["gate"] != 100 or counts["diagnostic"] != 33:
        raise SystemExit(
            "prompt set is not the registered 133/100/33 shape: %s" % counts
        )
    if args.dry_run:
        print(json.dumps({
            "prompts": args.prompts,
            "sha256": sha256_file(args.prompts),
            "counts": counts,
            "max_prompt_bytes": max(r["prompt_bytes"] for r in prompts),
            "sample_bytes": args.max_new_bytes,
        }, indent=2))
        return

    if not args.checkpoint:
        raise SystemExit("--checkpoint is required unless --dry-run")

    from pipeline.merge import load_model_mmap

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    os.makedirs(os.path.dirname(args.meta_out) or ".", exist_ok=True)
    os.makedirs(os.path.dirname(args.log) or ".", exist_ok=True)

    def log(line):
        with open(args.log, "a") as f:
            f.write(line + "\n")
        print(line, flush=True)

    wanted = [p.strip() for p in args.ids.split(",") if p.strip()]
    if wanted:
        by_id = {r["id"]: r for r in prompts}
        missing = [p for p in wanted if p not in by_id]
        if missing:
            raise SystemExit("unknown ids: %s" % ", ".join(missing))
        prompts = [by_id[p] for p in wanted]
    if args.limit:
        prompts = prompts[: args.limit]

    done = set()
    if args.resume and os.path.exists(args.out):
        with open(args.out) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    done.add(json.loads(line)["id"])
                except Exception:
                    continue
        log("resume: %d rows already in %s" % (len(done), args.out))
    rows_resumed = len(done)

    device = torch.device(args.device)
    model, cfg = load_model_mmap(args.checkpoint)
    if args.dtype != "auto":
        model = model.to(getattr(torch, args.dtype))
    model = model.to(device).eval()
    dtype = str(next(model.parameters()).dtype).replace("torch.", "")
    block = model.config.block_size
    if block is not None:
        worst = max(r["prompt_bytes"] for r in prompts) + args.max_new_bytes
        if worst > block:
            raise SystemExit(
                "longest prompt + sample = %d > block_size %d" % (worst, block)
            )

    ckpt_sha = None
    if args.hash_checkpoint:
        log("hashing checkpoint %s ..." % args.checkpoint)
        ckpt_sha = sha256_file(args.checkpoint)
        log("checkpoint sha256: %s" % ckpt_sha)

    meta = {
        "schema": "key2_generation",
        "started_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "checkpoint": args.checkpoint,
        "checkpoint_bytes": os.path.getsize(args.checkpoint),
        "checkpoint_mtime": int(os.path.getmtime(args.checkpoint)),
        "checkpoint_sha256": ckpt_sha,
        "prompts": args.prompts,
        "prompts_sha256": sha256_file(args.prompts),
        "prompt_counts": counts,
        "max_new_bytes": args.max_new_bytes,
        "decoding": "greedy argmax, temperature 0, one sample per prompt",
        "block_size": block,
        "device": str(device),
        "dtype": dtype,
        "torch": torch.__version__,
        "cuda": torch.version.cuda,
        "hostname": platform.node(),
        "git_head": git_head(),
        "rows": 0,
        "rows_resumed": rows_resumed,
        "rows_written": 0,
        "rows_total": rows_resumed,
    }
    log("### key2 generation start %s" % meta["started_at"])
    log("checkpoint: %s (%d bytes, mtime %d)"
        % (args.checkpoint, meta["checkpoint_bytes"], meta["checkpoint_mtime"]))
    log("prompts: %s (%d prompts, sha256 %s)"
        % (args.prompts, len(prompts), meta["prompts_sha256"]))
    log("decoding: %s | max_new_bytes=%d | block=%s | device=%s | dtype=%s"
        % (meta["decoding"], args.max_new_bytes, block, device, dtype))

    t0 = time.time()
    written = 0
    with open(args.out, "a") as out:
        for i, p in enumerate(prompts, 1):
            if p["id"] in done:
                log("[%d/%d] %s skipped (resume)" % (i, len(prompts), p["id"]))
                continue
            ts = time.time()
            sample = greedy_bytes(
                model, p["prompt"].encode("utf-8"), args.max_new_bytes, device
            )
            dt = time.time() - ts
            row = {
                "id": p["id"],
                "family": p["family"],
                "gate": p["gate"],
                "prompt": p["prompt"],
                "prompt_bytes": p["prompt_bytes"],
                "prompt_sha256": p["prompt_sha256"],
                "sample_hex": sample.hex(),
                "sample_text": sample.decode("utf-8", errors="replace"),
                "sample_bytes": len(sample),
                "sample_sha256": hashlib.sha256(sample).hexdigest(),
                "elapsed_s": round(dt, 3),
                "bytes_per_s": round(len(sample) / dt, 3) if dt else None,
                "checkpoint": args.checkpoint,
                "decoding": "greedy_argmax",
                "max_new_bytes": args.max_new_bytes,
            }
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
            out.flush()
            written += 1
            if i == 1 or i % 10 == 0:
                log("[%d/%d] %s %.2fs %.2f B/s | %r"
                    % (i, len(prompts), p["id"], dt,
                       len(sample) / dt if dt else 0.0,
                       row["sample_text"][:80]))
            meta["rows"] = written
            meta["rows_written"] = written
            meta["rows_total"] = rows_resumed + written
            if written % 10 == 0:
                with open(args.meta_out, "w") as f:
                    json.dump(meta, f, indent=2, ensure_ascii=False)
                    f.write("\n")

    meta["finished_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    meta["wall_s"] = round(time.time() - t0, 1)
    with open(args.meta_out, "w") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)
        f.write("\n")
    log("wrote %s (%d rows, %.1fs, %.2f B/s aggregate)"
        % (args.out, written, meta["wall_s"],
           written * args.max_new_bytes / meta["wall_s"] if meta["wall_s"] else 0.0))


if __name__ == "__main__":
    main()
